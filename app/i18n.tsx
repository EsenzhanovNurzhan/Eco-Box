const translations: Record<Locale, Partial<Record<TranslationKey, string>>> = {
  ru: ruMessages,
  kk: kkMessages,
  en: enMessages,
};

const russianTextKeys = new Map<string, TranslationKey>();
for (const [key, value] of Object.entries(ruMessages) as [TranslationKey, string][]) {
  if (!russianTextKeys.has(value)) russianTextKeys.set(value, key);
}

type LocaleContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey) => string;
  tr: (russianText: string) => string;
};

const LocaleContext = createContext<LocaleContextValue | null>(null);

function isLocale(value: string | null): value is Locale {
  return value === "ru" || value === "kk" || value === "en";
}

function translate(locale: Locale, key: TranslationKey) {
  return translations[locale][key] ?? ruMessages[key];
}

function translateRussianText(locale: Locale, text: string) {
  const key = russianTextKeys.get(text);
  return key ? translate(locale, key) : text;
}

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("ru");
  const [initialized, setInitialized] = useState(false);

  useEffect(() => {
    const timeout = window.setTimeout(() => {
      try {
        const storedLocale = window.localStorage.getItem("ecobox-locale");
        if (isLocale(storedLocale)) setLocale(storedLocale);
      } catch {}
      setInitialized(true);
    }, 0);

    return () => window.clearTimeout(timeout);
  }, []);

  useEffect(() => {
    const syncMetadata = () => {
      document.documentElement.lang = locale;
      const title = translate(locale, "pageTitle");
      if (document.title !== title) document.title = title;
      const description = document.querySelector<HTMLMetaElement>('meta[name="description"]');
      const content = translate(locale, "pageDescription");
      if (description && description.content !== content) description.content = content;
    };

    syncMetadata();
    const observer = new MutationObserver(syncMetadata);
    observer.observe(document.head, {
      attributes: true,
      attributeFilter: ["content"],
      characterData: true,
      childList: true,
      subtree: true,
    });

    return () => observer.disconnect();
  }, [locale]);

  useEffect(() => {
    if (!initialized) return;

    try {
      window.localStorage.setItem("ecobox-locale", locale);
    } catch {}
  }, [initialized, locale]);

  const value: LocaleContextValue = {
    locale,
    setLocale,
    t: (key) => translate(locale, key),
    tr: (text) => translateRussianText(locale, text),
  };

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>;
}

export function useLocale() {
  const value = useContext(LocaleContext);
  if (!value) throw new Error("useLocale must be used inside LocaleProvider");
  return value;
}

export function LanguageSwitcher() {
  const { locale, setLocale, t } = useLocale();

  return (
    <label className="language-switcher">
      <span className="sr-only">{t("language")}</span>
      <select value={locale} onChange={(event) => setLocale(event.target.value as Locale)} aria-label={t("language")}>
        <option value="ru">RU</option>
        <option value="kk">ҚАЗ</option>
        <option value="en">EN</option>
      </select>
    </label>
  );
}